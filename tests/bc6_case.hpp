// ВСЕ исходные данные кейса BC6 — откольного опыта на карбиде бора.
// Постановка: contact/06-e2e-bc6.md.
//
// Здесь и только здесь живут числа, описывающие сам физический опыт:
// размеры тел, материалы, плотности, скорость удара, зазор, разрешение,
// длительность расчёта, положение мониторов и допуски приёмки §6.
// Построение геометрии — в bc6_geometry.hpp, проверки — в test_e2e_bc6.cpp.
// Параметры РЕШАТЕЛЯ (CFL, псевдовязкость, t_total полного режима, save_t)
// лежат отдельно, в tests/data/bc6_initial_conditions.txt, и разбираются
// боевым parse_sph_config(): так тест проходит через реальный путь загрузки
// конфигурации, а не выставляет поля в обход него.
//
// Ни одно число отсюда не дублируется в BC2 и не берётся из него.
//
// ЕДИНИЦЫ: метры, секунды, м/с, кг/м³. Постановка записана в миллиметрах и
// микросекундах, поэтому каждая константа снабжена исходным значением.

#include <array>
#include <cstddef>

namespace bc6
{

// ===========================================================================
// Тела сборки (§2.2, §2.7)
// ===========================================================================
struct BodySpec
{
    const char* name;
    double T;       // паспортная толщина, м
    double R;       // радиус, м
    double rho0;    // кг/м³
    int    itype;   // материал
    double vz;      // начальная осевая скорость, м/с
    bool   gap_after;   // после этого тела идёт фиксированный зазор удара
};

// Скорость удара (§2.7): 913 м/с. Тела 1 и 2 (снаряд) летят, 3 и 4 покоятся.
inline constexpr double kVImpact = 913.0;

// МАТЕРИАЛЫ. Новых заводить не потребовалось, вопреки предположению §2.6
// постановки: реестр include/materials.hpp уже содержит все три.
//   itype 6  — полиуретан 160: ровно та пена, что нужна подложке;
//   itype 9  — PMMA: и ударник, и окно (они нигде не соприкасаются, значит
//              одного номера достаточно);
//   itype 10 — B4C, модель JH-2.
// Плотность ρ₀ НЕ берётся из таблицы материалов: конвейер ставит
// rho_0[i] = rho[i] при построении, поэтому паспортные плотности опыта
// задаются здесь и попадают в расчёт напрямую.
//
// Оговорка по PMMA. Константы itype 9 (aa = 1.8797e9, zz = 4.668) отвечают
// c₀ = 2720 м/с и s = 1.417, тогда как справочная ударная адиабата из §2.6 —
// 2598 + 1.516·up. Расхождение около 5 %. Постановка это допускает прямо:
// приведённые в ней значения помечены как справочные, «при наличии своих
// использовать их». Влияет в основном на период лесенки (допуск §6 — ±0.15
// мкс при значении 0.88), поэтому принято как есть, а materials.hpp не
// правится.
inline constexpr int kItypeFoam = 6;
inline constexpr int kItypePMMA = 9;
inline constexpr int kItypeB4C  = 10;

inline constexpr std::array<BodySpec, 4> kBodies{{
    // имя                     T, м        R, м       rho0     itype        vz  зазор
    {"подложка (пена 160)",  8.000e-3,  43.75e-3,   160.0, kItypeFoam, kVImpact, false},
    {"ударник (PMMA)",       2.004e-3,  43.75e-3,  1186.0, kItypePMMA, kVImpact, true },
    {"образец (B4C)",       10.526e-3,  38.05e-3,  2506.0, kItypeB4C,       0.0, false},
    {"окно (PMMA)",         24.200e-3,  38.05e-3,  1186.0, kItypePMMA,      0.0, false},
}};

inline constexpr size_t kSampleBody = 2;   // образец B4C — тело №3, индекс 2

// ===========================================================================
// Решётка (§2.3)
// ===========================================================================
inline constexpr double kDxFull  = 2.0e-4;   // 0.2 мм
inline constexpr double kDxSmoke = 8.0e-4;   // 0.8 мм

// ЕДИНСТВЕННЫЙ настоящий зазор — на плоскости удара, между телами 2 и 3.
// Фиксирован в миллиметрах и НЕ кратен шагу решётки. Это принципиально: при
// h = 2Δx носитель кубического сплайна равен 4Δx = 0.8 мм, то есть зазор
// «4Δx», стоявший в BC2, в точности совпадал с радиусом носителя, и тела
// «видели» друг друга уже при t = 0. Зазор 1.0 мм строго больше носителя,
// поэтому снаряд и мишень при t = 0 действительно разделены, а момент удара
// считается точно и не зависит от разрешения.
inline constexpr double kImpactGap = 1.000e-3;

// Тела, находящиеся в контакте (1↔2 и 3↔4), раскладываются в единую решётку:
// первый слой следующего тела ставится на Δx дальше последнего слоя
// предыдущего. Это не зазор, а продолжение решётки с тем же межчастичным
// расстоянием.

// ===========================================================================
// Длительность расчёта (§2.7, §4)
// ===========================================================================
// Полный режим берёт t_total из конфигурации (4.3e-6). Smoke укорачивает:
// это решение испытательной обвязки, а не параметр кейса. 1e-6 выбрано так,
// чтобы фронт успел дойти до монитора и smoke проверял не только запуск
// (у BC2 здесь стояло 3e-7, при котором монитор тождественно нулевой).
inline constexpr double kTTotalSmoke = 1.0e-6;

// ===========================================================================
// Мониторы (§2.4, §5.1)
// ===========================================================================
// Оба — на тыльном слое образца (тело 3, i_z = n_z − 1).
// Основной на оси (i_r = 0); контрольный на r = 12.5 мм нужен для
// сопоставимости с BC2 и как индикатор потери одномерности.
inline constexpr double kMoniCtlRadius = 12.5e-3;

// ===========================================================================
// Ожидаемые времена (§5.3)
// ===========================================================================
// Продольная скорость звука в B4C из паспорта опыта (Приложение): 14.07 км/с.
inline constexpr double kClB4C = 14070.0;
// Момент удара: закрытие зазора 1.0 мм со скоростью 913 м/с. От разрешения
// не зависит — в этом и был смысл фиксированного зазора.
inline constexpr double kTImpact = kImpactGap / kVImpact;   // 1.0953e-6 с

// ===========================================================================
// Допуски приёмки (§6)
// ===========================================================================
inline constexpr double kFrontTol    = 5.0e-8;   // ±0.05 мкс на приход фронта
inline constexpr double kPlateau1Lo  = 170.0;    // §6: уровень плато 1, м/с
inline constexpr double kPlateau1Hi  = 190.0;
inline constexpr double kStepRatio   = 0.82;     // §6: отношение соседних ступеней
inline constexpr double kStepRatioTol = 0.02;
inline constexpr double kPeriod      = 0.88e-6;  // §6: период лесенки, с
inline constexpr double kPeriodTol   = 0.15e-6;
// Порог «скорость монитора равна нулю» до момента удара (§6).
//
// Точный ноль здесь требовать нельзя, и это выяснилось измерением: при
// contact_force_type = 0, то есть при полностью выключенных контактных силах,
// монитор набирает 0.016 м/с начиная с 0.84 мкс. Причина не в контакте, а в
// самом методе: носитель ядра имеет конечный радиус, зазор 1.0 мм попадает
// внутрь него задолго до номинального момента удара, и слабое взаимодействие
// через хвост ядра начинается раньше. Это свойство SPH, а не дефект.
//
// Поэтому порог выбран содержательно: 1 м/с — это 0.6 % от уровня плато и
// втрое ниже приборного разрешения опыта (≈3 м/с, §5.2), то есть заведомо
// ниже всего, что вообще можно было бы измерить. При этом чувствительности
// с огромным запасом хватает на то, ради чего проверка и стоит: паразитный
// импульс от штрафной силы на равновесном расстоянии дал бы скачок порядка
// 10^4 м/с (именно так это выглядело на BC2 до исправления радиуса частицы).
inline constexpr double kQuietVel    = 1.0;      // м/с

// ===========================================================================
// Реперные точки эталона (§5.2), измеренные по tests/data/bc6_reference.txt
// ===========================================================================
// Используются только самопроверкой извлекателя лесенки: он обязан
// воспроизвести опубликованный профиль. Допуски — из §5.2: ±0.003 км/с по
// скорости и ±0.02 мкс по времени, причём приборное разрешение (≈3 м/с) не
// даёт сделать их жёстче.
inline constexpr double kRefTolV   = 3.0;      // м/с
inline constexpr double kRefTolT   = 2.0e-8;   // с
inline constexpr double kRefPeak      = 182.85;
inline constexpr double kRefPlateau1  = 171.52;
inline constexpr double kRefPlateau2  = 141.19;
inline constexpr double kRefPlateau3  = 115.84;
inline constexpr double kRefDip1V     = 114.93;
inline constexpr double kRefDip1T     = 1.989958e-6;
inline constexpr double kRefDip2V     = 105.79;
inline constexpr double kRefDip2T     = 2.860374e-6;

} // namespace bc6
