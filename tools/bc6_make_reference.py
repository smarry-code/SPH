#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Конвертер приборного эталона кейса BC6 в формат, который читает e2e-тест.

    python3 tools/bc6_make_reference.py

Источник   : Керамика/Карбид бора/BC6/BC6.txt  (архив кейса, две колонки)
Результат  : tests/data/bc6_reference.txt      (три колонки + шапка)

Почему отдельный скрипт, а не режим теста. У BC2 флаг --emit-reference печатает
кривую, снятую САМИМ расчётом; здесь же речь о переносе приборной записи из
архива. Тот же глагол для другой операции запутывал бы: приборный эталон BC2
тоже получен внешней конвертацией (contact/e2e/gold_standart.txt), а не этим
флагом. Вдобавок источник лежит вне дерева сборки, по пути с кириллицей и среди
файлов в cp1251 — ставить цель CMake в зависимость от него незачем.

Что делает скрипт:
  1. читает две колонки (время, с) и (скорость, м/с) — пересчёта единиц НЕТ;
  2. УСТОЙЧИВО сортирует по времени;
  3. дописывает третью колонку itype = 10 (B4C), как в эталоне BC2;
  4. считает реперные точки и вписывает их в шапку.

Строки не выбрасываются и не сливаются: все 236 точек попадают в результат.
"""

import os
import statistics
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "Керамика", "Карбид бора", "BC6", "BC6.txt")
OUT = os.path.join(ROOT, "tests", "data", "bc6_reference.txt")

MONITOR_ITYPE = 10  # B4C: монитор стоит на тыльном слое образца


def read_source(path):
    rows = []
    with open(path, "r", encoding="ascii", errors="strict") as fh:
        for lineno, line in enumerate(fh, 1):
            line = line.strip()
            if not line:
                continue
            parts = line.split()
            if len(parts) != 2:
                raise SystemExit("%s:%d: ожидались две колонки, получено %d"
                                 % (path, lineno, len(parts)))
            rows.append((float(parts[0]), float(parts[1])))
    return rows


def count_inversions(rows):
    return sum(1 for a, b in zip(rows, rows[1:]) if b[0] < a[0])


def plateau(rows, t0, t1):
    vals = [v for t, v in rows if t0 <= t <= t1]
    return statistics.median(vals), len(vals)


def dip(rows, t0, t1):
    window = [(t, v) for t, v in rows if t0 <= t <= t1]
    return min(window, key=lambda tv: tv[1])


def main():
    if not os.path.exists(SRC):
        raise SystemExit("не найден источник: %s" % SRC)

    raw = read_source(SRC)
    inversions = count_inversions(raw)
    rows = sorted(raw, key=lambda tv: tv[0])  # sorted устойчив

    peak_t, peak_v = max(rows, key=lambda tv: tv[1])

    # Окна взяты из §5.2 постановки (время по шкале опыта).
    p1, n1 = plateau(rows, 1.13e-6, 1.93e-6)
    p2, n2 = plateau(rows, 2.10e-6, 2.78e-6)
    p3, n3 = plateau(rows, 2.95e-6, 3.25e-6)
    d1_t, d1_v = dip(rows, 1.94e-6, 2.06e-6)
    d2_t, d2_v = dip(rows, 2.80e-6, 2.94e-6)

    # Фронт: первое пересечение 10 % пика.
    t_front = next(t for t, v in rows if v >= 0.10 * peak_v)

    lines = []
    add = lines.append
    add("# ===========================================================================")
    add("# Приборный эталон кейса BC6: осевая скорость границы «керамика / окно».")
    add("#")
    add("# Формат: <время, с>  <v_z, м/с>  <itype>   — тот же, что у log.txt расчёта")
    add("# и у tests/data/bc2_reference.txt, поэтому читается тем же read_curve().")
    add("# itype = %d (B4C): монитор стоит на тыльном слое образца." % MONITOR_ITYPE)
    add("#")
    add("# Источник: Керамика/Карбид бора/BC6/BC6.txt (архив кейса).")
    add("# Сгенерировано: tools/bc6_make_reference.py. Правки вносить в скрипт,")
    add("# а не в этот файл.")
    add("#")
    add("# Единицы источника уже совпадают с нужными (с и м/с) — пересчёта нет.")
    add("# Строк в источнике: %d; в этом файле: %d — ни одна не отброшена." % (len(raw), len(rows)))
    add("#")
    add("# ЧТО ИЗМЕНЕНО ПРОТИВ ИСТОЧНИКА: только порядок строк.")
    add("# В источнике %d строк идут не по возрастанию времени. Все они лежат на" % inversions)
    add("# переднем фронте — почти вертикальном участке, оцифрованном как облако")
    add("# точек в окне ~0.7 нс со значениями от 11 до 131 м/с. Это артефакт")
    add("# оцифровки вертикали, а не измерение. Строки УСТОЙЧИВО отсортированы по")
    add("# времени; ни одна точка не удалена, не сдвинута и не усреднена.")
    add("#")
    add("# Практическое следствие. Признаки фронта (10/50/90 %) ищутся назад от")
    add("# пика, поэтому все три уровня попадают в последний скачок облака и дают")
    add("# длительность фронта ~9 нс. Это разрешение оцифровки, а не физическая")
    add("# крутизна. Сравнивать с ней длительность фронта расчёта, размазанного")
    add("# ядром SPH на десятки наносекунд, бессмысленно — поэтому ворота по фронту")
    add("# для BC6 выключены, а осмысленной проверкой служит момент ПРИХОДА фронта")
    add("# (§6: 1.83 ± 0.05 мкс) и метрики лесенки.")
    add("#")
    add("# НАЧАЛО ОТСЧЁТА ВРЕМЕНИ ПРОИЗВОЛЬНО. Времена прихода первой волны в этих")
    add("# опытах не измерялись (§5.2 постановки), поэтому абсолютный сдвиг между")
    add("# этой шкалой и расчётной (около 0.73 мкс) физического смысла не имеет и в")
    add("# метрику входить не должен. Сверка ведётся после совмещения по фронту.")
    add("#")
    add("# ТОЧНОСТЬ. Оцифровка: ±0.003 км/с и ±0.02 мкс. Прибор: константа")
    add("# интерферометра 121.34 м/с на полосу при разрешении около 2 % полосы, то")
    add("# есть детали мельче ≈3 м/с смысла не имеют. Допуски сверки не должны быть")
    add("# жёстче этого.")
    add("#")
    add("# РЕПЕРНЫЕ ТОЧКИ, измеренные по этому файлу (их воспроизведение —")
    add("# самопроверка extract_staircase в tests/test_e2e_bc6.cpp):")
    add("#   окно записи      : %.6e … %.6e с" % (rows[0][0], rows[-1][0]))
    add("#   фронт (10 %% пика): %.6e с" % t_front)
    add("#   пик (выброс)     : %.2f м/с при %.6e с" % (peak_v, peak_t))
    add("#   плато 1          : %.2f м/с (медиана по %d точкам, 1.13…1.93 мкс)" % (p1, n1))
    add("#   провал 1         : %.2f м/с при %.6e с" % (d1_v, d1_t))
    add("#   плато 2          : %.2f м/с (медиана по %d точкам, 2.10…2.78 мкс)" % (p2, n2))
    add("#   провал 2         : %.2f м/с при %.6e с" % (d2_v, d2_t))
    add("#   плато 3          : %.2f м/с (медиана по %d точкам, 2.95…3.25 мкс)" % (p3, n3))
    add("#   отношения ступеней: %.3f и %.3f   (§5.2: 0.826 и 0.818)" % (p2 / p1, p3 / p2))
    add("#   период лесенки    : %.3f и %.3f мкс (§5.2: 0.89 и 0.87)"
        % ((d1_t - t_front) * 1e6, (d2_t - d1_t) * 1e6))
    add("#   возврат после провалов: +%.2f и +%.2f м/с" % (p2 - d1_v, p3 - d2_v))
    add("#")
    add("# Отдельно: утверждение §5.2 постановки «в репозитории отсутствует BC6.txt»")
    add("# неверно — файл лежит в архиве кейса и является источником этого эталона.")
    add("# ===========================================================================")

    for t, v in rows:
        lines.append("%.9e %.6f %d" % (t, v, MONITOR_ITYPE))

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")

    sys.stderr.write("записано: %s (%d строк данных, %d строк шапки)\n"
                     % (OUT, len(rows), len(lines) - len(rows)))
    sys.stderr.write("инверсий времени в источнике: %d\n" % inversions)
    sys.stderr.write("плато %.2f / %.2f / %.2f; отношения %.3f / %.3f\n"
                     % (p1, p2, p3, p2 / p1, p3 / p2))
    sys.stderr.write("провалы %.2f @ %.4e и %.2f @ %.4e\n" % (d1_v, d1_t, d2_v, d2_t))
    sys.stderr.write("период %.3f / %.3f мкс\n"
                     % ((d1_t - t_front) * 1e6, (d2_t - d1_t) * 1e6))


if __name__ == "__main__":
    main()
